import type { Abi } from "viem";

export interface Deployment {
  contractName: string;
  chainId: number;
  address: `0x${string}`;
  deployedAt: string;
  deployer: `0x${string}`;
  boardId?: string;
  roles: {
    admin?: `0x${string}`;
    supplier: `0x${string}`;
    assembler: `0x${string}`;
    auditor: `0x${string}`;
    custodian: `0x${string}`;
  };
  demo?: {
    boardId: string;
    componentIds: string[];
    expected: { compliant: boolean; missing: string[] };
  };
  abi: readonly unknown[];
}

/**
 * Which deployment this build talks to, selected at build time:
 *   VITE_DEPLOYMENT_CHAIN=84532 vite build   -> Base Sepolia
 *   (unset)                                    -> local Hardhat node (31337)
 *
 * The files are generated by scripts/seed.ts (local) and
 * scripts/seed-base-sepolia.ts (testnet); never hand-copy an address into a
 * component. Vite watches the folder, so redeploying hot-reloads this module.
 */
const CHAIN_FILE = (import.meta.env.VITE_DEPLOYMENT_CHAIN as string | undefined) ?? "31337";

const deployments = import.meta.glob("../../../shared/deployments/*.json", {
  eager: true,
  import: "default",
});

const selected = deployments[`../../../shared/deployments/${CHAIN_FILE}.json`] as
  | Record<string, unknown>
  | undefined;

if (!selected) {
  throw new Error(
    `No deployment for chain ${CHAIN_FILE}. Run the seed script first ` +
      `(bun run seed:local for 31337, bun run seed:base for 84532), ` +
      `then rebuild with VITE_DEPLOYMENT_CHAIN=${CHAIN_FILE}.`,
  );
}

export const deployment = selected as unknown as Deployment;

export const CHAIN_ID = deployment.chainId;
export const ABI = deployment.abi as Abi;
export const CONTRACT_ADDRESS = deployment.address;

/** Where the same-origin /api/rpc proxy should forward local reads. */
export const LOCAL_RPC_URL = "http://127.0.0.1:8545";
